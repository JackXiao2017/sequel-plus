static NSString * const SPQuotedOrders = @"\"Sales Data\".\"Orders \"\"x\"\" 2026\"";

@interface SPPostgresTableActionsTests : XCTestCase
@property (strong) NSMutableArray<PGPostgresConnection *> *openConnections;
@end

@implementation SPPostgresTableActionsTests

+ (NSArray<NSString *> *)cleanupStatements
{
	return @[
		@"DROP MATERIALIZED VIEW IF EXISTS public.sp9_matview",
		@"DROP VIEW IF EXISTS public.sp9_dep",
		@"DROP VIEW IF EXISTS public.sp9_view",
		@"DROP TABLE IF EXISTS public.sp9_child",
		@"DROP TABLE IF EXISTS public.sp9_a, public.sp9_b, public.sp9_base, public.sp9_other, public.sp9_made, public.sp9_txn",
		@"DROP TABLE IF EXISTS public.\"orders \"\"x\"\" 2026\"",
		@"DROP TABLE IF EXISTS \"Sales Data\".\"Orders \"\"x\"\" 2026\"",
		@"DROP TABLE IF EXISTS public.\"Orders \"\"x\"\" 2026\"",
		@"DROP SCHEMA IF EXISTS \"sp9_a\"\"b\"",
	];
}

- (void)cleanUp
{
	for (NSNumber *port in [SPPostgresTestServers ports]) {
		PGPostgresConnection *connection = [SPPostgresTestServers connectedConnectionOnPort:port.unsignedIntegerValue];
		[connection execute:@"ROLLBACK"];
		[connection execute:@"SET lock_timeout = '10s'"];
		for (NSString *sql in [[self class] cleanupStatements]) [connection execute:sql];
		[connection disconnect];
	}
}

- (void)setUp
{
	self.continueAfterFailure = NO;
	self.openConnections = [NSMutableArray array];
	[self cleanUp];
}

- (void)tearDown
{
	for (PGPostgresConnection *connection in self.openConnections) [connection disconnect];
	self.openConnections = nil;
	[self cleanUp];
	[super tearDown];
}

#pragma mark - Helpers

- (void)forEachServer:(void (^)(PGPostgresConnection *connection, NSNumber *port))block
{
	for (NSNumber *port in [SPPostgresTestServers ports]) {
		PGPostgresConnection *connection = [SPPostgresTestServers connectedConnectionOnPort:port.unsignedIntegerValue];
		XCTAssertNotNil(connection);
		[self.openConnections addObject:connection];
		block(connection, port);
	}
}

- (void)run:(NSString *)sql on:(PGPostgresConnection *)connection
{
	XCTAssertNotNil([connection execute:sql], @"%@: %@", sql, connection.lastError.errorPrimaryMessage);
}

- (NSString *)value:(NSString *)sql on:(PGPostgresConnection *)connection
{
	PGPostgresResult *result = [connection execute:sql];
	XCTAssertNotNil(result, @"%@: %@", sql, connection.lastError.errorPrimaryMessage);
	id text = result.numberOfRows ? [result textValueAtRow:0 column:0] : nil;
	return [text isKindOfClass:[NSString class]] ? text : nil;
}

/// YES when relation (a regclass text, e.g. public.sp9_a) exists
- (BOOL)exists:(NSString *)relation on:(PGPostgresConnection *)connection
{
	return [[self value:[NSString stringWithFormat:@"SELECT to_regclass(%@ )::text", [self literal:relation]] on:connection] length] > 0;
}

- (NSString *)literal:(NSString *)text
{
	return [NSString stringWithFormat:@"'%@'", [text stringByReplacingOccurrencesOfString:@"'" withString:@"''"]];
}

#pragma mark - Tests

- (void)testTruncateEmptiesTables
{
	[self forEachServer:^(PGPostgresConnection *connection, NSNumber *port) {
		[self run:@"CREATE TABLE public.sp9_a (id integer PRIMARY KEY, v text)" on:connection];
		[self run:@"CREATE TABLE public.sp9_b (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)" on:connection];
		[self run:@"INSERT INTO public.sp9_a VALUES (1, 'x'), (2, 'y')" on:connection];
		[self run:@"INSERT INTO public.sp9_b VALUES (DEFAULT), (DEFAULT), (DEFAULT)" on:connection];

		NSError *error = nil;
		BOOL done = [SPPostgresTableActions truncateTables:@[@"sp9_a", @"sp9_b"] inSchema:@"public" connection:connection error:&error];
		XCTAssertTrue(done, @"%d: %@", port.intValue, error);

		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM public.sp9_a" on:connection], @"0");
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM public.sp9_b" on:connection], @"0");
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM pg_attribute WHERE attrelid IN ('public.sp9_a'::regclass, 'public.sp9_b'::regclass) AND attnum > 0 AND NOT attisdropped" on:connection], @"3");
		// no RESTART IDENTITY: the identity sequence goes on
		[self run:@"INSERT INTO public.sp9_b VALUES (DEFAULT)" on:connection];
		XCTAssertEqualObjects([self value:@"SELECT id::text FROM public.sp9_b" on:connection], @"4");
	}];
}

- (void)testDropTablesViewsAndMaterializedViews
{
	[self forEachServer:^(PGPostgresConnection *connection, NSNumber *port) {
		[self run:@"CREATE TABLE public.sp9_a (id integer)" on:connection];
		[self run:@"CREATE VIEW public.sp9_view AS SELECT 1 AS one" on:connection];
		[self run:@"CREATE MATERIALIZED VIEW public.sp9_matview AS SELECT 1 AS one" on:connection];

		NSError *error = nil;
		BOOL done = [SPPostgresTableActions dropRelations:@[@"sp9_a", @"sp9_view", @"sp9_matview"] inSchema:@"public" connection:connection error:&error];
		XCTAssertTrue(done, @"%d: %@", port.intValue, error);
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM pg_class WHERE relname IN ('sp9_a', 'sp9_view', 'sp9_matview') AND relnamespace = 'public'::regnamespace" on:connection], @"0");
	}];
}

