- (void)testCreateTableMatchesSpec
{
	[self forEachServer:^(PGPostgresConnection *connection, NSNumber *port) {
		NSError *error = nil;
		XCTAssertTrue([SPPostgresTableActions createTableNamed:@"sp9_made" inSchema:@"public" connection:connection error:&error], @"%d: %@", port.intValue, error);

		XCTAssertEqualObjects([self value:@"SELECT format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = 'public.sp9_made'::regclass AND attname = 'id'" on:connection], @"integer");
		XCTAssertEqualObjects([self value:@"SELECT attidentity::text FROM pg_attribute WHERE attrelid = 'public.sp9_made'::regclass AND attname = 'id'" on:connection], @"d");
		XCTAssertEqualObjects([self value:@"SELECT pg_get_constraintdef(oid) FROM pg_constraint WHERE conrelid = 'public.sp9_made'::regclass AND contype = 'p'" on:connection], @"PRIMARY KEY (id)");
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM pg_attribute WHERE attrelid = 'public.sp9_made'::regclass AND attnum > 0" on:connection], @"1");

		NSError *second = nil;
		XCTAssertFalse([SPPostgresTableActions createTableNamed:@"sp9_made" inSchema:@"public" connection:connection error:&second]);
		XCTAssertNotNil(second);
	}];
}

- (void)testActionsQuoteSchemaAndName
{
	[self forEachServer:^(PGPostgresConnection *connection, NSNumber *port) {
		NSString *name = @"Orders \"x\" 2026";
		NSError *error = nil;
		// decoys in public: the same name in lower case and with its exact case, each with a row
		[self run:@"CREATE TABLE public.\"Orders \"\"x\"\" 2026\" (id integer)" on:connection];
		[self run:@"INSERT INTO public.\"Orders \"\"x\"\" 2026\" VALUES (1)" on:connection];
		[self run:@"CREATE TABLE public.\"orders \"\"x\"\" 2026\" (id integer)" on:connection];
		[self run:@"INSERT INTO public.\"orders \"\"x\"\" 2026\" VALUES (1)" on:connection];

		XCTAssertTrue([SPPostgresTableActions createTableNamed:name inSchema:@"Sales Data" connection:connection error:&error], @"%d: %@", port.intValue, error);
		[self run:[NSString stringWithFormat:@"INSERT INTO %@ VALUES (1), (2)", SPQuotedOrders] on:connection];

		BOOL truncated = [SPPostgresTableActions truncateTables:@[name] inSchema:@"Sales Data" connection:connection error:&error];
		XCTAssertTrue(truncated, @"%@", error);
		NSString *countSQL = [NSString stringWithFormat:@"SELECT count(*)::text FROM %@", SPQuotedOrders];
		XCTAssertEqualObjects([self value:countSQL on:connection], @"0");
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM public.\"orders \"\"x\"\" 2026\"" on:connection], @"1");

		BOOL dropped = [SPPostgresTableActions dropRelations:@[name] inSchema:@"Sales Data" connection:connection error:&error];
		XCTAssertTrue(dropped, @"%@", error);
		XCTAssertFalse([self exists:SPQuotedOrders on:connection]);
		XCTAssertTrue([self exists:@"public.\"orders \"\"x\"\" 2026\"" on:connection]);
		XCTAssertTrue([self exists:@"public.\"Orders \"\"x\"\" 2026\"" on:connection]);
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM public.\"Orders \"\"x\"\" 2026\"" on:connection], @"1");
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM public.\"orders \"\"x\"\" 2026\"" on:connection], @"1");
	}];
}

- (void)testActionsInsideUserTransaction
{
	[self forEachServer:^(PGPostgresConnection *connection, NSNumber *port) {
		[self run:@"CREATE TABLE public.sp9_txn (id integer)" on:connection];
		[self run:@"CREATE TABLE public.sp9_other (id integer)" on:connection];

		[self run:@"BEGIN" on:connection];
		NSError *error = nil;
		XCTAssertTrue([SPPostgresTableActions dropRelations:@[@"sp9_txn"] inSchema:@"public" connection:connection error:&error], @"%d: %@", port.intValue, error);
		// the transaction is still open: the drop is inside it and a rollback brings the table back
		XCTAssertFalse([self exists:@"public.sp9_txn" on:connection]);
		[self run:@"ROLLBACK" on:connection];
		XCTAssertTrue([self exists:@"public.sp9_txn" on:connection]);

		// an aborted transaction: refused, nothing sent
		[self run:@"BEGIN" on:connection];
		XCTAssertNil([connection execute:@"SELECT * FROM public.sp9_no_such_table"]);
		NSError *refused = nil;
		XCTAssertFalse([SPPostgresTableActions dropRelations:@[@"sp9_other"] inSchema:@"public" connection:connection error:&refused]);
		XCTAssertNotNil(refused);
		XCTAssertFalse([SPPostgresTableActions truncateTables:@[@"sp9_other"] inSchema:@"public" connection:connection error:&refused]);
		XCTAssertFalse([SPPostgresTableActions createTableNamed:@"sp9_made" inSchema:@"public" connection:connection error:&refused]);
		[self run:@"ROLLBACK" on:connection];
		XCTAssertTrue([self exists:@"public.sp9_other" on:connection]);
		XCTAssertFalse([self exists:@"public.sp9_made" on:connection]);
	}];
}

- (void)testActionsQuoteSchemaWithQuote
{
	[self forEachServer:^(PGPostgresConnection *connection, NSNumber *port) {
		[self run:@"CREATE SCHEMA \"sp9_a\"\"b\"" on:connection];
		NSError *error = nil;
		BOOL created = [SPPostgresTableActions createTableNamed:@"t1" inSchema:@"sp9_a\"b" connection:connection error:&error];
		XCTAssertTrue(created, @"%d: %@", port.intValue, error);
		[self run:@"INSERT INTO \"sp9_a\"\"b\".t1 VALUES (1), (2)" on:connection];
		BOOL truncated = [SPPostgresTableActions truncateTables:@[@"t1"] inSchema:@"sp9_a\"b" connection:connection error:&error];
		XCTAssertTrue(truncated, @"%@", error);
		XCTAssertEqualObjects([self value:@"SELECT count(*)::text FROM \"sp9_a\"\"b\".t1" on:connection], @"0");
		BOOL dropped = [SPPostgresTableActions dropRelations:@[@"t1"] inSchema:@"sp9_a\"b" connection:connection error:&error];
		XCTAssertTrue(dropped, @"%@", error);
		XCTAssertFalse([self exists:@"\"sp9_a\"\"b\".t1" on:connection]);
		[self run:@"DROP SCHEMA \"sp9_a\"\"b\"" on:connection];
	}];
}

- (void)testFailedDropInOpenTransactionKeepsTransactionUsable
{
	[self forEachServer:^(PGPostgresConnection *connection, NSNumber *port) {
		[self run:@"CREATE TABLE public.sp9_base (id integer)" on:connection];
		[self run:@"CREATE VIEW public.sp9_dep AS SELECT id FROM public.sp9_base" on:connection];

		[self run:@"BEGIN" on:connection];
		NSError *error = nil;
		BOOL done = [SPPostgresTableActions dropRelations:@[@"sp9_base"] inSchema:@"public" connection:connection error:&error];
		XCTAssertFalse(done);
		XCTAssertEqual(error.code, SPPostgresErrorHasDependents);
		// the transaction is open and not aborted
		XCTAssertEqualObjects([self value:@"SELECT 1::text" on:connection], @"1");
		[self run:@"CREATE TABLE public.sp9_txn (id integer)" on:connection];
		[self run:@"ROLLBACK" on:connection];
		XCTAssertTrue([self exists:@"public.sp9_base" on:connection]);
		// the table made inside the transaction went with the rollback: it had been open all along
		XCTAssertFalse([self exists:@"public.sp9_txn" on:connection]);
	}];
}

